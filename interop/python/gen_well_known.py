"""Regenerate protoc/well_known.odin from Google's well-known-type descriptors.

The embedded .proto sources are rebuilt from the descriptors shipped with
Google's protobuf runtime (structure, file options, explicit json_name), so
the descriptors odin-protoc embeds for them are byte-identical to Google's.
Reference bytes are written to tests/protoc/testdata/wkt for the test.

Usage (from the repository root):
    interop/python/.venv/Scripts/python -I interop/python/gen_well_known.py
"""

import os

from google.protobuf import (
    any_pb2,
    descriptor_pb2,
    duration_pb2,
    empty_pb2,
    field_mask_pb2,
    struct_pb2,
    timestamp_pb2,
    wrappers_pb2,
)

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MODULES = [empty_pb2, timestamp_pb2, duration_pb2, wrappers_pb2, any_pb2, field_mask_pb2, struct_pb2]
SCALARS = {
    1: "double", 2: "float", 3: "int64", 4: "uint64", 5: "int32", 6: "fixed64", 7: "fixed32",
    8: "bool", 9: "string", 12: "bytes", 13: "uint32", 15: "sfixed32", 16: "sfixed64",
    17: "sint32", 18: "sint64",
}


def relative(type_name, pkg):
    prefix = "." + pkg + "."
    return type_name[len(prefix):] if type_name.startswith(prefix) else type_name


def option_value(field, value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return '"%s"' % value
    if field.enum_type is not None:
        return field.enum_type.values_by_number[value].name
    return str(value)


def source_of(d):
    pkg = d.package
    lines = ['syntax = "proto3";', "", f"package {pkg};", ""]
    for field, value in d.options.ListFields():
        lines.append(f"option {field.name} = {option_value(field, value)};")
    lines.append("")
    entries = {}
    for msg in d.message_type:
        for nested in msg.nested_type:
            if nested.options.map_entry:
                entries[f".{pkg}.{msg.name}.{nested.name}"] = nested

    def type_of(f):
        return relative(f.type_name, pkg) if f.type in (11, 14) else SCALARS[f.type]

    # json_name is not written: odin-protoc records it for every field of
    # these files (Google's descriptors do), see File.all_json_names.
    def json(f):
        return ""

    for msg in d.message_type:
        lines.append(f"message {msg.name} {{")
        emitted_oneofs = set()
        for f in msg.field:
            if f.HasField("oneof_index"):
                if f.oneof_index in emitted_oneofs:
                    continue
                emitted_oneofs.add(f.oneof_index)
                lines.append(f"  oneof {msg.oneof_decl[f.oneof_index].name} {{")
                for g in msg.field:
                    if g.HasField("oneof_index") and g.oneof_index == f.oneof_index:
                        lines.append(f"    {type_of(g)} {g.name} = {g.number}{json(g)};")
                lines.append("  }")
            elif f.type == 11 and f.type_name in entries:
                key, value = entries[f.type_name].field
                lines.append(f"  map<{type_of(key)}, {type_of(value)}> {f.name} = {f.number}{json(f)};")
            else:
                label = "repeated " if f.label == 3 else ""
                lines.append(f"  {label}{type_of(f)} {f.name} = {f.number}{json(f)};")
        lines.append("}")
        lines.append("")
    for e in d.enum_type:
        lines.append(f"enum {e.name} {{")
        for v in e.value:
            lines.append(f"  {v.name} = {v.number};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    out = [
        "// Code generated by interop/python/gen_well_known.py. DO NOT EDIT.",
        "",
        "package protoc",
        "",
        "// Embedded_Source is a .proto file compiled into odin-protoc so that imports",
        "// of common well-known types resolve without a protobuf include directory.",
        "Embedded_Source :: struct {",
        "\tpath:   string,",
        "\tsource: string,",
        "}",
        "",
        "// WELL_KNOWN_TYPES reproduce the google.protobuf well-known types exactly",
        "// (fields and file options; json_name is recorded for every field), so the descriptors",
        "// odin-protoc embeds for them are byte-identical to Google's.",
        "WELL_KNOWN_TYPES := [?]Embedded_Source {",
    ]
    wkt_dir = os.path.join(ROOT, "tests", "protoc", "testdata", "wkt")
    os.makedirs(wkt_dir, exist_ok=True)
    for m in MODULES:
        d = descriptor_pb2.FileDescriptorProto.FromString(m.DESCRIPTOR.serialized_pb)
        out += ["\t{", f'\t\t"{d.name}",', "\t\t`" + source_of(d) + "`,", "\t},"]
        name = os.path.basename(d.name).replace(".proto", ".desc.bin")
        with open(os.path.join(wkt_dir, name), "wb") as f:
            f.write(m.DESCRIPTOR.serialized_pb)
    out.append("}")
    path = os.path.join(ROOT, "protoc", "well_known.odin")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(path, ROOT)} and {len(MODULES)} reference descriptors")


if __name__ == "__main__":
    main()
